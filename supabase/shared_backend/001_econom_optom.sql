create index if not exists econom_products_sku_idx on public.econom_products(sku);
create index if not exists econom_order_requests_created_idx on public.econom_order_requests(created_at desc);
create index if not exists econom_order_requests_status_idx on public.econom_order_requests(status);
create index if not exists econom_supplier_events_status_received_idx on public.econom_supplier_events(status, received_at);

