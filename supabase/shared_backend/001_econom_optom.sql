create extension if not exists pgcrypto;

create table if not exists public.econom_products (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'victoria_forsage',
  source_id text not null unique,
  sku text not null,
  slug text not null unique,
  name text not null,
  category text,
  brand text,
  gender text,
  season text,
  material text,
  unit_price_uah numeric(12,2) not null check (unit_price_uah >= 0),
  pack_size integer not null check (pack_size > 0),
  size_grid text,
  image_urls jsonb not null default '[]'::jsonb,
  attributes jsonb not null default '{}'::jsonb,
  source_url text,
  is_active boolean not null default true,
  source_updated_at timestamptz,
  last_synced_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.econom_order_requests (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity,
  company_name text not null,
  contact_name text not null,
  phone text not null,
  city text not null,
  delivery_method text,
  comment text,
  total_uah numeric(12,2) not null default 0,
  status text not null default 'new' check (status in ('new','confirmed','awaiting_payment','paid','assembling','shipped','completed','cancelled')),
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.econom_sync_runs (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'victoria_forsage',
  status text not null check (status in ('running','success','partial','failed')),
  received integer not null default 0,
  created_count integer not null default 0,
  updated_count integer not null default 0,
  archived_count integer not null default 0,
  error_count integer not null default 0,
  errors jsonb not null default '[]'::jsonb,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table if not exists public.econom_supplier_events (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'victoria_forsage',
  product_ids jsonb not null default '[]'::jsonb,
  change_types jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','processing','processed','failed')),
  attempts integer not null default 0,
  last_error text,
  received_at timestamptz not null default now(),
  processed_at timestamptz
);

